    Hij = F[:orb_i, orb_i:]
    Sij = S[:orb_i, orb_i:]

    eps_i, psi_i = eigh(Hii, Sii, subset_by_index=[lo, hi])
    eps_j, psi_j = eigh(Hjj, Sjj, subset_by_index=[lo, hi])

    H_ab = float(psi_i.T @ Hij @ psi_j)
    S_ab = float(psi_i.T @ Sij @ psi_j)
